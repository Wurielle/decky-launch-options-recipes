#!/usr/bin/env python3
"""Regenerate self-contained entrypoints after editing the three runtime modules.

Run: python3 -I -B recipes/dlor-optiscaler/scripts/update-source-hashes.py
Review/commit the resulting entrypoints with the modules in the same revision.
No network, archive payload, shared runner or generated catalog is touched.
The recipe-local bootstrap digest in index.ts is refreshed when present.
"""
from pathlib import Path
import hashlib
import json
import re

HERE = Path(__file__).resolve().parent
MODULES = ('installer.py', 'artifacts.py', 'game_discovery.py')

SHELL = r'''#!/usr/bin/env bash
# Generated by update-source-hashes.py; edit that generator, not this file.
# Host cleanup is scoped to auxiliary subprocesses, never the game environment.
host_exec() {
    unset LD_PRELOAD PYTHONHOME PYTHONPATH
    if [[ ${STEAM_RUNTIME:-} == /* ]]; then
        export PATH="${SYSTEM_PATH:-/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin}"
        export LD_LIBRARY_PATH="${SYSTEM_LD_LIBRARY_PATH:-}"
        unset STEAM_RUNTIME
    fi
    exec "$@"
}
host() ( host_exec "$@" )
start_log() {
    local log_dir="$HOME/.dlor/logs/dlor-optiscaler/$1" stamp candidate excess
    logger_pid=''
    exec {console_out}>&1 {console_err}>&2
    if host mkdir -p -- "$log_dir"; then
        stamp=$(host date -u +%Y%m%dT%H%M%S.%N)-$$
        if (umask 077; : > "$log_dir/$stamp.log"); then
            # Keep the pipe reader alive even if tee cannot start/write; logging
            # must not turn preparation or the eventual game into SIGPIPE.
            exec > >(
                if ! host tee --output-error=warn -- "$log_dir/$stamp.log" >&"$console_out" 2>&"$console_err"; then
                    printf 'Warning: logger failed; continuing on console.\n' >&"$console_err"
                    while IFS= read -r line || [[ -n $line ]]; do
                        printf '%s\n' "$line" >&"$console_out"
                    done
                fi
            ) 2>&1
            logger_pid=$!
            (
                export LC_ALL=C
                shopt -s nullglob
                logs=()
                for candidate in "$log_dir/"*.log; do
                    [[ -f $candidate && ! -L $candidate ]] && logs+=("$candidate")
                done
                excess=$(( ${#logs[@]} - 10 ))
                if (( excess > 0 )); then
                    host rm -f -- "${logs[@]:0:excess}" || printf 'Warning: log retention failed; continuing.\n' >&2
                fi
            )
        else
            printf 'Warning: logging unavailable; continuing.\n' >&2
        fi
    else
        printf 'Warning: logging unavailable; continuing.\n' >&2
    fi
}
finish_log() {
    printf 'DLOR OptiScaler %s exit status: %s\n' "$entry_name" "$1"
    exec 1>&"$console_out" 2>&"$console_err"
    [[ -z $logger_pid ]] || wait "$logger_pid" || :
    exec {console_out}>&- {console_err}>&-
}
'''

PYTHON_COMMON = r'''
import hashlib, importlib.abc, importlib.util, json, os, pathlib, re, signal, stat, subprocess, sys, tempfile

active_child = None

def cancel_auxiliary(signum, frame):
    # Each bounded auxiliary command has its own process group. Never signal the
    # game/Steam process group, and reap children before removing handoff files.
    signal.signal(signal.SIGINT, signal.SIG_IGN)
    signal.signal(signal.SIGTERM, signal.SIG_IGN)
    if active_child is not None:
        try:
            os.killpg(active_child.pid, signum)
        except ProcessLookupError:
            pass
    # Do not call Popen.wait from a signal handler: a signal can interrupt
    # communicate while its non-reentrant waitpid lock is held. Reap on unwind.
    raise SystemExit(128 + signum)

signal.signal(signal.SIGINT, cancel_auxiliary)
signal.signal(signal.SIGTERM, cancel_auxiliary)

def run_auxiliary(command, data=None):
    global active_child
    active_child = subprocess.Popen(command, stdin=subprocess.PIPE if data is not None else subprocess.DEVNULL,
                                    start_new_session=True)
    try:
        active_child.communicate(input=data)
        if active_child.returncode:
            raise subprocess.CalledProcessError(active_child.returncode, command)
    except BaseException:
        try:
            active_child.wait(timeout=2)
        except subprocess.TimeoutExpired:
            os.killpg(active_child.pid, signal.SIGKILL)
            active_child.wait()
        raise
    finally:
        active_child = None

def private_directory(path):
    path = pathlib.Path(path)
    for part in [*reversed(path.parents), path]:
        if not part.exists() and not part.is_symlink():
            try: part.mkdir(mode=0o700)
            except FileExistsError: pass
        info = part.lstat()
        if stat.S_ISLNK(info.st_mode) or not stat.S_ISDIR(info.st_mode):
            raise ValueError('unsafe cache directory: ' + str(part))
    info = path.stat()
    if info.st_uid != os.getuid() or info.st_mode & 0o077:
        raise ValueError('source cache must be private and user owned: ' + str(path))
    return path

def source_context():
    revision = os.environ.get('DLOR_OPTISCALER_SOURCE_REVISION', os.environ.get('DLOR_SCRIPT_REVISION', ''))
    repository = os.environ.get('DLOR_OPTISCALER_SOURCE_REPOSITORY', os.environ.get('DLOR_REPOSITORY', 'Wurielle/decky-launch-options-recipes'))
    if not re.fullmatch(r'[a-f0-9]{40}', revision):
        raise ValueError('invalid DLOR_SCRIPT_REVISION: expected a full lowercase Git commit')
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*', repository):
        raise ValueError('invalid DLOR_REPOSITORY')
    cache = private_directory(pathlib.Path.home().resolve(strict=True) / '.dlor/cache/dlor-optiscaler/source' / revision)
    base = 'https://raw.githubusercontent.com/' + repository + '/' + revision + '/recipes/dlor-optiscaler/scripts/'
    return cache, base

def verified_file(cache, base, name, digest):
    if not re.fullmatch(r'[a-f0-9]{64}', digest):
        raise ValueError('invalid source digest for ' + name)
    path = cache / name
    if path.is_symlink() or (path.exists() and not path.is_file()):
        raise ValueError('unsafe source cache file: ' + str(path))
    if path.is_file():
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() == digest:
            return data
        print('Source cache checksum mismatch; fetching ' + name, file=sys.stderr)
    fd, temporary = tempfile.mkstemp(prefix='.' + name + '.', dir=cache)
    os.close(fd)
    try:
        run_auxiliary(['curl', '-fL', '--silent', '--show-error', '--connect-timeout', '15',
                       '--max-time', '180', '--proto', '=https', '--tlsv1.2', '-o', temporary,
                       base + name])
        data = pathlib.Path(temporary).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError('source checksum mismatch: ' + name)
        os.replace(temporary, path)
        return data
    finally:
        try: os.unlink(temporary)
        except FileNotFoundError: pass

# -B prevents writes, not reads: compile the verified bytes rather than trusting
# importlib's timestamp-based .pyc cache, including any preexisting __pycache__.
class VerifiedSource(importlib.abc.MetaPathFinder, importlib.abc.Loader):
    def __init__(self, cache, sources):
        self.cache, self.sources = cache, sources
    def find_spec(self, fullname, path=None, target=None):
        if fullname in self.sources:
            return importlib.util.spec_from_loader(fullname, self, origin=str(self.cache / (fullname + '.py')))
    def create_module(self, spec):
        return None
    def exec_module(self, module):
        module.__file__ = str(self.cache / (module.__name__ + '.py'))
        exec(compile(self.sources[module.__name__], module.__file__, 'exec'), module.__dict__)
'''


def render_entry(action, hashes):
    code = 'SOURCE_SHA256 = ' + repr(hashes) + '\n' + PYTHON_COMMON + r'''
try:
    cache, base = source_context()
    sources = {name[:-3]: verified_file(cache, base, name, digest) for name, digest in SOURCE_SHA256.items()}
    sys.meta_path.insert(0, VerifiedSource(cache, sources))
    import installer
    status = installer.main([ACTION, *sys.argv[1:]])
    sys.exit(0 if status is None else status)
except Exception as error:
    print('DLOR OptiScaler: ' + str(error), file=sys.stderr)
    sys.exit(1)
'''
    code = 'ACTION = ' + repr(action) + '\n' + code
    return (SHELL + f"\nentry_name={action}\nstart_log \"$entry_name\"\n"
            + "host python3 -I -B -c '" + code.replace("'", "'\\''") + "' \"$@\"\n"
            + 'status=$?\nfinish_log "$status"\nexit "$status"\n')


def render_launch(hashes):
    code = 'ENTRY_SHA256 = ' + repr(hashes) + '\n' + PYTHON_COMMON + r'''
try:
    work = pathlib.Path(sys.argv[1])
    game_argv = sys.argv[2:]
    if not game_argv:
        raise ValueError('missing original game argv')
    action = os.environ.get('DLOR_OPTISCALER_ACTION', '')
    if action not in ('install', 'uninstall'):
        raise ValueError('invalid DLOR_OPTISCALER_ACTION')
    root = os.environ.get('STEAM_COMPAT_INSTALL_PATH', '')
    if not root:
        raise ValueError('STEAM_COMPAT_INSTALL_PATH is required')
    cache, base = source_context()
    entries = {name: verified_file(cache, base, name, digest) for name, digest in ENTRY_SHA256.items()}
    argv_file = work / 'argv.json'
    argv_file.write_text(json.dumps(game_argv))
    result_file = work / 'result.json'
    command = ['bash', '-s', '--', root, '--argv-file', str(argv_file)]
    if action == 'install':
        command += ['--result', str(result_file)]
    run_auxiliary(command, data=entries[action + '.sh'])
    if action == 'install':
        if result_file.is_symlink() or not result_file.is_file():
            raise ValueError('installer did not publish a fresh result')
        result = json.loads(result_file.read_text())
        proxy = result.get('proxy')
        if proxy not in ('dxgi', 'winmm', 'version', 'd3d12', 'dbghelp', 'wininet', 'winhttp') or not isinstance(result.get('target'), str) or not result['target']:
            raise ValueError('invalid installer result')
        original = os.environ.get('WINEDLLOVERRIDES', '')
        merged = []
        for entry in original.split(';') if original else []:
            names, separator, value = entry.partition('=')
            parts = names.split(',')
            remaining = [part for part in parts if part.strip().lower().removeprefix('*').removesuffix('.dll') != proxy]
            if len(parts) == len(remaining) or not separator:
                merged.append(entry)
            elif remaining:
                merged.append(','.join(remaining) + separator + value)
        merged.append(proxy + '=n,b')
        (work / 'wine').write_bytes(';'.join(merged).encode() + b'\0')
except Exception as error:
    print('DLOR OptiScaler: ' + str(error) + '; continuing original game.', file=sys.stderr)
    sys.exit(1)
'''
    return (SHELL + r'''
# Function-local bookkeeping is restored before exec, including names that
# happened to be exported by another launch option in the original environment.
dlor_optiscaler_launch_main() {
local entry_name=launch work='' helper_pid='' status=0 merged='' logger_pid='' console_out console_err
start_log "$entry_name"
work=''
cleanup() {
    [[ -z $work ]] || host rm -rf -- "$work" || printf 'Warning: launch cleanup failed.\n' >&2
    work=''
}
helper_pid=''
cancel_launch() {
    local signum=$1 code=$2
    trap '' INT TERM
    if [[ -n $helper_pid ]]; then
        kill -"$signum" "$helper_pid" 2>/dev/null || :
        wait "$helper_pid" || :
        helper_pid=''
    fi
    cleanup
    finish_log "$code"
    exit "$code"
}
trap 'cancel_launch INT 130' INT
trap 'cancel_launch TERM 143' TERM
work=$(host mktemp -d "${TMPDIR:-$HOME/.dlor}/dlor-optiscaler.XXXXXXXX")
status=$?
if [[ -n $work && $status == 0 ]]; then
    host_exec python3 -I -B -c ''' + "'" + code.replace("'", "'\\''") + "'" + r''' "$work" "$@" &
    helper_pid=$!
    wait "$helper_pid"
    status=$?
    helper_pid=''
    if [[ $status == 0 && -f $work/wine && ! -L $work/wine ]]; then
        if IFS= read -r -d '' merged < "$work/wine"; then
            export WINEDLLOVERRIDES="$merged"
        fi
    fi
fi
cleanup
if (( $# == 0 )); then
    printf 'DLOR OptiScaler: missing original game argv.\n' >&2
    finish_log 2
    trap - INT TERM
    exit 2
fi
finish_log "$status"
trap - INT TERM
}
dlor_optiscaler_launch_main "$@"
exec "$@"
''')


def main():
    hashes = {name: hashlib.sha256((HERE / name).read_bytes()).hexdigest() for name in MODULES}
    for action in ('install', 'uninstall'):
        (HERE / (action + '.sh')).write_text(render_entry(action, hashes))
    entries = {name: hashlib.sha256((HERE / name).read_bytes()).hexdigest() for name in ('install.sh', 'uninstall.sh')}
    launch = render_launch(entries)
    (HERE / 'launch.sh').write_text(launch)
    digest = hashlib.sha256(launch.encode()).hexdigest()
    index = HERE.parent / 'index.ts'
    if index.is_file():
        source, count = re.subn(r"const launchSha256 = '[a-f0-9]{64}'",
                                "const launchSha256 = '" + digest + "'", index.read_text())
        if count != 1:
            raise ValueError('expected one launchSha256 constant in index.ts')
        index.write_text(source)
    print(json.dumps({'SOURCE_SHA256': hashes, 'ENTRY_SHA256': entries, 'LAUNCH_SHA256': digest}, indent=2))


if __name__ == '__main__':
    main()
