#!/usr/bin/env python3
"""Refresh the physical loader manifest and SHA-pinned shell entrypoints.

Run: python3 -I -B recipes/dlor-optiscaler/scripts/update-source-hashes.py
Review/commit the resulting entrypoints with the modules in the same revision.
No network, archive payload, shared runner or generated catalog is touched.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re

HERE = Path(__file__).resolve().parent
MODULES = ('installer.py', 'artifacts.py', 'game_discovery.py', 'update_optiscaler_config.py', 'nightly.py')

# The runtime bundle is independently immutable; outer scripts can be revised
# without putting acquisition metadata into the game's launch options.
previous_entry = (HERE / 'install.sh').read_text() if (HERE / 'install.sh').exists() else ''
previous_revision = re.search(r'^BUNDLE_REVISION=([a-f0-9]{40})$', previous_entry, re.M)
previous_repository = re.search(r'^BUNDLE_REPOSITORY=([A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+)$', previous_entry, re.M)
BUNDLE_REVISION = previous_revision[1] if previous_revision else '8f744ceb877b9da85a55d161e25fae26b2c112eb'
BUNDLE_REPOSITORY = previous_repository[1] if previous_repository else 'Wurielle/decky-launch-options-recipes'

SHELL = r'''#!/usr/bin/env bash
# Generated by update-source-hashes.py; edit that generator, not this file.
# Host cleanup is scoped to auxiliary subprocesses, never the game environment.
host_exec() {
    unset LD_PRELOAD PYTHONHOME PYTHONPATH
    if [[ ${STEAM_RUNTIME:-} == /* ]]; then
        export PATH="${SYSTEM_PATH:-/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin}"
        export LD_LIBRARY_PATH="${SYSTEM_LD_LIBRARY_PATH:-}"
        unset STEAM_RUNTIME
    fi
    exec "$@"
}
host() ( host_exec "$@" )
start_log() {
    local log_dir="$HOME/.dlor/logs/dlor-optiscaler/$1" stamp candidate excess
    logger_pid=''
    exec {console_out}>&1 {console_err}>&2
    if host mkdir -p -- "$log_dir"; then
        stamp=$(host date -u +%Y%m%dT%H%M%S.%N)-$$
        if (umask 077; : > "$log_dir/$stamp.log"); then
            # Keep the pipe reader alive even if tee cannot start/write; logging
            # must not turn preparation or the eventual game into SIGPIPE.
            exec > >(
                if ! host tee --output-error=warn -- "$log_dir/$stamp.log" >&"$console_out" 2>&"$console_err"; then
                    printf 'Warning: logger failed; continuing on console.\n' >&"$console_err"
                    while IFS= read -r line || [[ -n $line ]]; do
                        printf '%s\n' "$line" >&"$console_out"
                    done
                fi
            ) 2>&1
            logger_pid=$!
            (
                export LC_ALL=C
                shopt -s nullglob
                logs=()
                for candidate in "$log_dir/"*.log; do
                    [[ -f $candidate && ! -L $candidate ]] && logs+=("$candidate")
                done
                excess=$(( ${#logs[@]} - 10 ))
                if (( excess > 0 )); then
                    host rm -f -- "${logs[@]:0:excess}" || printf 'Warning: log retention failed; continuing.\n' >&2
                fi
            )
        else
            printf 'Warning: logging unavailable; continuing.\n' >&2
        fi
    else
        printf 'Warning: logging unavailable; continuing.\n' >&2
    fi
}
finish_log() {
    printf 'DLOR OptiScaler %s exit status: %s\n' "$entry_name" "$1"
    exec 1>&"$console_out" 2>&"$console_err"
    [[ -z $logger_pid ]] || wait "$logger_pid" || :
    exec {console_out}>&- {console_err}>&-
}
'''

BOOTSTRAP = r'''
run_loader() (
    umask 077
    private_work=''
    download_pid=''
    cleanup_loader() {
        [[ -z $download_pid ]] || { kill -KILL "$download_pid" 2>/dev/null || :; wait "$download_pid" 2>/dev/null || :; }
        [[ -z $private_work ]] || host rm -rf -- "$private_work"
        :
    }
    trap cleanup_loader EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    revision=${DLOR_OPTISCALER_SOURCE_REVISION-$BUNDLE_REVISION}
    repository=${DLOR_OPTISCALER_SOURCE_REPOSITORY-$BUNDLE_REPOSITORY}
    export DLOR_OPTISCALER_SOURCE_REVISION=$revision
    export DLOR_OPTISCALER_SOURCE_REPOSITORY=$repository
    # Actions belong to the physical entrypoint, not ambient game assignments.
    unset DLOR_OPTISCALER_ACTION DLOR_OPTISCALER_LATEST
    if [[ $entry_name == install ]]; then export SteamDeck=0; fi
    if [[ ! $revision =~ ^[a-f0-9]{40}$ ||
          ! $repository =~ ^[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*$ ||
          ! $MANIFEST_SHA256 =~ ^[a-f0-9]{64}$ ]]; then
        printf 'DLOR OptiScaler: invalid source revision, repository or digest\n' >&2
        return 1
    fi
    # Resolve only trusted HOME, never a controlled cache component.
    IFS= read -r -d '' canonical_home < <(host readlink -ez -- "$HOME") || return 1
    cache=$canonical_home
    for part in .dlor cache dlor-optiscaler source "$revision"; do
        cache=$cache/$part
        if [[ ! -e $cache && ! -L $cache ]]; then
            host mkdir -m 700 -- "$cache" || [[ -d $cache ]] || return 1
        fi
        if [[ -L $cache || ! -d $cache ]]; then
            printf 'DLOR OptiScaler: unsafe cache directory: %s\n' "$cache" >&2
            return 1
        fi
    done
    attributes=$(host stat -c '%u:%a' -- "$cache") || return 1
    owner=${attributes%%:*}
    mode=${attributes#*:}
    if [[ ! $owner =~ ^[0-9]+$ || ! $mode =~ ^[0-7]{3,4}$ ]]; then
        printf 'DLOR OptiScaler: invalid cache ownership or mode metadata\n' >&2
        return 1
    fi
    if [[ $owner != "$EUID" ]] || (( (8#$mode & 077) != 0 )); then
        printf 'DLOR OptiScaler: source cache must be private and user owned: %s\n' "$cache" >&2
        return 1
    fi
    # Refuse redirected source files before even the loader network request.
    for name in downloads.json loader.py installer.py artifacts.py game_discovery.py update_optiscaler_config.py nightly.py; do
        if [[ -L $cache/$name || ( -e $cache/$name && ! -f $cache/$name ) ]]; then
            printf 'DLOR OptiScaler: unsafe source cache file: %s\n' "$cache/$name" >&2
            return 1
        fi
    done
    private_work=$(host mktemp -d "$cache/.loader.XXXXXXXX") || return 1
    verify_source() {
        local actual
        actual=$(host sha256sum < "$1") || return 1
        [[ ${actual%% *} == "$2" ]]
    }
    snapshot_source() {
        local name=$1 expected=$2
        if [[ ! -f $cache/$name ]] || ! verify_source "$cache/$name" "$expected"; then
            printf 'Source cache checksum mismatch or missing; fetching %s\n' "$name" >&2
            ( host_exec curl -fL --silent --show-error --connect-timeout 15 --max-time 180 \
                --proto '=https' --proto-redir '=https' --max-redirs 5 --tlsv1.2 \
                -o "$private_work/download" \
                "https://raw.githubusercontent.com/$repository/$revision/recipes/dlor-optiscaler/scripts/$name" </dev/null ) &
            download_pid=$!
            wait "$download_pid"
            status=$?
            download_pid=''
            (( status == 0 )) || return "$status"
            verify_source "$private_work/download" "$expected" || { printf 'DLOR OptiScaler: %s checksum mismatch\n' "$name" >&2; return 1; }
            host mv -f -- "$private_work/download" "$cache/$name" || return 1
        fi
        host cp -- "$cache/$name" "$private_work/$name" || return 1
        verify_source "$private_work/$name" "$expected" || { printf 'DLOR OptiScaler: %s snapshot checksum mismatch\n' "$name" >&2; return 1; }
        host chmod 400 -- "$private_work/$name" || return 1
    }
    snapshot_source downloads.json "$MANIFEST_SHA256" || return $?
    # Parse only a canonical digest line from already authenticated JSON, using
    # builtins: no unverified Python/JSON parser executes to establish trust.
    loader_digest='' digest_lines=0
    while IFS= read -r line; do
        if [[ $line =~ ^[[:space:]]*\"loader.py\":\ \"([a-f0-9]{64})\",?$ ]]; then
            loader_digest=${BASH_REMATCH[1]}
            (( digest_lines += 1 ))
        fi
    done < "$private_work/downloads.json"
    (( digest_lines == 1 )) || { printf 'DLOR OptiScaler: invalid loader manifest entry\n' >&2; return 1; }
    snapshot_source loader.py "$loader_digest" || return $?
    DLOR_OPTISCALER_MANIFEST="$private_work/downloads.json" \
    DLOR_OPTISCALER_MANIFEST_SHA256="$MANIFEST_SHA256" \
        host python3 -I -B "$private_work/loader.py" "$entry_name" "$@"
)
'''


def render_entry(action, manifest_hash, source_revision=BUNDLE_REVISION, source_repository=BUNDLE_REPOSITORY):
    body = ('run_loader "$@"\nstatus=$?\n')
    if action == 'upgrade':
        body = r'''if [[ $# == 1 && ( $1 == --help || $1 == -h ) ]]; then
    printf 'Usage: bash update-nightly.sh /path/to/steam-game-directory\n'
    printf 'Updates the latest official nightly through DLOR ownership or legacy fgmod.\n'
    status=0
elif [[ $# != 1 || ! -d $1 ]]; then
    printf 'Error: missing or invalid game directory: %s\n' "${1-}" >&2
    status=1
else
    run_loader "$@"
    status=$?
fi
(( status == 0 )) || printf 'Nightly upgrade failed; the runner will continue the game.\n' >&2
printf 'optiscaler/update-nightly finished with exit status %s.\n' "$status"
'''
    return (SHELL + '\nBUNDLE_REVISION=' + source_revision + '\nBUNDLE_REPOSITORY=' + source_repository
            + '\nMANIFEST_SHA256=' + manifest_hash + '\n' + BOOTSTRAP
            + f'\nentry_name={action}\nstart_log "$entry_name"\n'
            + body + 'finish_log "$status"\nexit "$status"\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-revision', default=BUNDLE_REVISION)
    parser.add_argument('--source-repository', default=BUNDLE_REPOSITORY)
    args = parser.parse_args()
    if not re.fullmatch(r'[a-f0-9]{40}', args.source_revision):
        parser.error('source revision must be a full lowercase Git commit')
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*', args.source_repository):
        parser.error('source repository must be owner/repository')
    manifest_path = HERE / 'downloads.json'
    manifest = json.loads(manifest_path.read_bytes()) if manifest_path.exists() else {'version': 1, 'downloads': {}}
    runtime = {name: hashlib.sha256((HERE / name).read_bytes()).hexdigest()
               for name in ('loader.py', *MODULES)}
    manifest['runtime'] = runtime
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n')
    manifest_hash = hashlib.sha256(manifest_path.read_bytes()).hexdigest()
    for action in ('install', 'uninstall'):
        (HERE / (action + '.sh')).write_text(render_entry(action, manifest_hash, args.source_revision, args.source_repository))
    nightly_entry = HERE.parent.parent / 'optiscaler/scripts/update-nightly.sh'
    if nightly_entry.parent.is_dir():
        nightly_entry.write_text(render_entry('upgrade', manifest_hash, args.source_revision, args.source_repository).replace(
            '/logs/dlor-optiscaler/', '/logs/optiscaler/').replace(
            'start_log "$entry_name"', 'start_log update-nightly').replace(
            'Warning: logging unavailable; continuing.', 'Warning: could not enable logging; continuing.').replace(
            'Warning: log retention failed; continuing.', 'Warning: could not remove old logs; continuing.'))
    print(json.dumps({'runtime': runtime, 'MANIFEST_SHA256': manifest_hash}, indent=2))


if __name__ == '__main__':
    main()
